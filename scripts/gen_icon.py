#!/usr/bin/env python3
"""Generates the OmniMap app icon for Desktop (SVG) and Android (vector drawable)
from one set of shapes, so the two never drift apart.

Android vector drawables can't draw dashed strokes, so every dash of the AI
"draft" elements is emitted as its own short sub-path.

    python3 scripts/gen_icon.py      # rewrites both files below
Then render the PNG with any SVG renderer at 512x512 (transparent background).
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SVG_OUT = ROOT / "packaging/linux/omnimap.svg"
ANDROID_OUT = ROOT / "androidApp/src/main/res/drawable/ic_launcher_foreground.xml"

INK, LAVENDER, GREY, ROSE, ORBIT = "#0F0D13", "#D0BCFF", "#CCC2DC", "#EFB8C8", "#49454F"

# Mesh: your committed thoughts (lavender / grey), solid links.
NODES = [((236, 262), 50, LAVENDER), ((156, 196), 30, GREY), ((306, 192), 32, LAVENDER), ((176, 352), 26, GREY)]
LINKS = [((236, 262), (156, 196)), ((236, 262), (306, 192)), ((156, 196), (306, 192)), ((236, 262), (176, 352))]
# The Architect: an orbit that turns into a dashed rose arc as it reaches a ghost (draft) node.
ORBIT_C, ORBIT_R = (232, 258), 161  # passes through the ghost node
GHOST_C, GHOST_R = (364, 350), 38
DRAFT_LINK = ((278, 290), (330, 324))


def f(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def pt(c, r, deg):
    a = math.radians(deg)
    return c[0] + r * math.cos(a), c[1] + r * math.sin(a)


def arc_path(c, r, a0, a1):
    """SVG path for a clockwise arc from angle a0 to a1 (degrees, screen coords)."""
    (x0, y0), (x1, y1) = pt(c, r, a0), pt(c, r, a1)
    large = 1 if (a1 - a0) % 360 > 180 else 0
    return f"M{f(x0)},{f(y0)}A{f(r)},{f(r)} 0,{large} 1,{f(x1)},{f(y1)}"


def dashed_arc(c, r, a0, a1, dash, gap):
    out, length_per_deg = [], math.pi * r / 180
    a = a0
    while a < a1 - 0.01:
        end = min(a + dash / length_per_deg, a1)
        out.append(arc_path(c, r, a, end))
        a = end + gap / length_per_deg
    return "".join(out)


def dashed_line(p0, p1, dash, gap):
    (x0, y0), (x1, y1) = p0, p1
    total = math.hypot(x1 - x0, y1 - y0)
    ux, uy = (x1 - x0) / total, (y1 - y0) / total
    out, d = [], 0.0
    while d < total - 0.01:
        e = min(d + dash, total)
        out.append(f"M{f(x0 + ux * d)},{f(y0 + uy * d)}L{f(x0 + ux * e)},{f(y0 + uy * e)}")
        d = e + gap
    return "".join(out)


def circle(c, r):
    return f"M{f(c[0] - r)},{f(c[1])}a{f(r)},{f(r)} 0,1 1,{f(2 * r)},0a{f(r)},{f(r)} 0,1 1,{f(-2 * r)},0"


# Each shape: (pathData, fill, fillAlpha, stroke, strokeWidth)
SHAPES = [
    (arc_path(ORBIT_C, ORBIT_R, 150, 252), None, 1, ORBIT, 10),
    (dashed_arc(ORBIT_C, ORBIT_R, 272, 360 + 19, 18, 16), None, 1, ROSE, 10),
    ("".join(f"M{a[0]},{a[1]}L{b[0]},{b[1]}" for a, b in LINKS), None, 1, LAVENDER, 12),
    (dashed_line(*DRAFT_LINK, 20, 18), None, 1, ROSE, 12),
    *[(circle(c, r), col, 1, None, 0) for c, r, col in NODES],
    (circle(GHOST_C, GHOST_R), ROSE, 0.16, None, 0),
    (dashed_arc(GHOST_C, GHOST_R, 0, 360, 24, 15), None, 1, ROSE, 12),
]


def write_svg():
    body = []
    for d, fill, alpha, stroke, width in SHAPES:
        attrs = f'fill="{fill}"' + (f' fill-opacity="{alpha}"' if alpha != 1 else "") if fill else 'fill="none"'
        if stroke:
            attrs += f' stroke="{stroke}" stroke-width="{width}" stroke-linecap="round"'
        body.append(f'  <path {attrs} d="{d}"/>')
    SVG_OUT.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512">\n'
        "  <!-- Generated by scripts/gen_icon.py: a web of thoughts, and the Architect proposing a new node. -->\n"
        f'  <rect x="32" y="32" width="448" height="448" rx="104" fill="{INK}"/>\n'
        '  <rect x="32.5" y="32.5" width="447" height="447" rx="103.5" fill="none" stroke="#2B2830" stroke-width="2"/>\n'
        + "\n".join(body) + "\n</svg>\n"
    )


def write_android():
    # Scale the 448px tile into the 66dp adaptive-icon safe zone, centred on (54, 54).
    s = 66 / 448
    t = 54 - 256 * s
    paths = []
    for d, fill, alpha, stroke, width in SHAPES:
        a = [f'android:pathData="{d}"']
        if fill:
            a.append(f'android:fillColor="{fill}"')
            if alpha != 1:
                a.append(f'android:fillAlpha="{alpha}"')
        if stroke:
            a += [f'android:strokeColor="{stroke}"', f'android:strokeWidth="{width}"', 'android:strokeLineCap="round"']
        paths.append("        <path\n            " + "\n            ".join(a) + " />")
    ANDROID_OUT.write_text(
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n\n'
        "    <!-- Generated by scripts/gen_icon.py. Edit that script, not this file. -->\n"
        f'    <group\n        android:scaleX="{s:.4f}"\n        android:scaleY="{s:.4f}"\n'
        f'        android:translateX="{t:.2f}"\n        android:translateY="{t:.2f}">\n'
        + "\n".join(paths) + "\n    </group>\n</vector>\n"
    )


if __name__ == "__main__":
    write_svg()
    write_android()
    print(f"wrote {SVG_OUT.relative_to(ROOT)} and {ANDROID_OUT.relative_to(ROOT)}")
